//! Embeds `skills/` into the `asc` binary so `asc skills` can install it
//! without the source tree.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let skills_dir = manifest_dir.join("../../skills");
    println!("cargo:rerun-if-changed={}", skills_dir.display());

    let skills_dir = skills_dir
        .canonicalize()
        .unwrap_or_else(|err| panic!("skills directory {}: {err}", skills_dir.display()));
    let mut files = Vec::new();
    collect(&skills_dir, &skills_dir, &mut files);
    if files.is_empty() {
        panic!("skills directory {} has no files", skills_dir.display());
    }
    files.sort_by(|left, right| left.0.cmp(&right.0));

    let mut source = String::from(
        "// Generated by build.rs. Do not edit.\n\
         pub struct SkillFile {\n\
         \x20   pub path: &'static str,\n\
         \x20   pub bytes: &'static [u8],\n\
         }\n\
         \npub static SKILL_FILES: &[SkillFile] = &[\n",
    );
    for (rel, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = fs::read(path)
            .unwrap_or_else(|err| panic!("read skill file {}: {err}", path.display()));
        source.push_str("    SkillFile {\n        path: ");
        source.push_str(&format!("{rel:?}"));
        source.push_str(",\n        bytes: &[");
        for (index, byte) in bytes.iter().enumerate() {
            if index % 16 == 0 {
                source.push_str("\n            ");
            }
            source.push_str(&format!("{byte},"));
        }
        source.push_str("\n        ],\n    },\n");
    }
    source.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let out = out_dir.join("skill_assets.rs");
    fs::write(&out, source)
        .unwrap_or_else(|err| panic!("write {}: {err}", out.display()));
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|err| panic!("read {}: {err}", dir.display()))
        .map(|entry| entry.unwrap_or_else(|err| panic!("read skill entry: {err}")))
        .collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        let rel = path
            .strip_prefix(root)
            .unwrap_or_else(|_| panic!("{} is outside {}", path.display(), root.display()));
        let rel = rel
            .components()
            .map(|component| component.as_os_str().to_string_lossy().into_owned())
            .collect::<Vec<_>>()
            .join("/");
        if rel.is_empty()
            || rel.split('/').any(|part| part.is_empty() || part == "." || part == "..")
        {
            panic!("skill path {rel} escapes the skills directory");
        }
        out.push((rel, path));
    }
}
